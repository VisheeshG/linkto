"use client";

import { useEffect, useState } from "react";
import { ChevronDown } from "lucide-react";
import {
  Button,
  CheckboxField,
  Dialog,
  Field,
  Input,
} from "@/components/ui";
import type { Link } from "@/lib/supabase";
import { canOpenInNativeApp } from "@/lib/mobile-app-redirect";
import { isoToLocalInput, localInputToIso } from "@/lib/datetime-input";

export type LinkFormValues = {
  link_title: string;
  platform: string;
  destination_url: string;
  open_app_on_mobile: boolean;
  include_submission_in_url: boolean;
  utm_enabled: boolean;
  expires_at: string | null;
};

const PLATFORM_SUGGESTIONS = [
  "Instagram",
  "YouTube",
  "TikTok",
  "X",
  "Facebook",
  "LinkedIn",
  "Snapchat",
  "Spotify",
  "Website",
  "Newsletter",
];

type Errors = Partial<Record<"link_title" | "platform" | "destination_url" | "open_app_on_mobile" | "expires_at", string>>;

function validate(values: LinkFormValues, expiresInput: string, isEdit: boolean): Errors {
  const errors: Errors = {};
  if (!values.link_title.trim()) errors.link_title = "Give the link a title.";
  if (!values.platform.trim()) errors.platform = "Enter the platform creators will post on.";
  const url = values.destination_url.trim();
  if (!url) {
    errors.destination_url = "Enter where the link should go.";
  } else {
    try {
      const parsed = new URL(url);
      if (!/^https?:$/.test(parsed.protocol)) errors.destination_url = "Use an http(s) URL.";
    } catch {
      errors.destination_url = "That doesn't look like a full URL (include https://).";
    }
  }
  if (values.open_app_on_mobile && !errors.destination_url && !canOpenInNativeApp(url)) {
    errors.open_app_on_mobile =
      "Open-in-app works with YouTube, Instagram, TikTok, X, Facebook and Spotify links.";
  }
  if (expiresInput) {
    const iso = localInputToIso(expiresInput);
    if (!iso) errors.expires_at = "Pick a valid date and time.";
    else if (!isEdit && new Date(iso) <= new Date()) errors.expires_at = "Choose a time in the future.";
  }
  return errors;
}

/**
 * Create or edit a link. Required fields first; the less common options
 * (submission in URL, open in app, UTM, expiry) live under "Advanced".
 */
export function LinkFormDialog({
  open,
  onClose,
  link,
  shortCodePreview,
  onSubmit,
}: {
  open: boolean;
  onClose: () => void;
  /** Present when editing. */
  link?: Link | null;
  /** Shown read-only when creating (generated by the caller). */
  shortCodePreview?: string;
  onSubmit: (values: LinkFormValues) => Promise<boolean>;
}) {
  const isEdit = Boolean(link);
  const [values, setValues] = useState<LinkFormValues>(() => initialValues(link));
  const [expiresInput, setExpiresInput] = useState("");
  const [errors, setErrors] = useState<Errors>({});
  const [showAdvanced, setShowAdvanced] = useState(false);
  const [submitting, setSubmitting] = useState(false);

  useEffect(() => {
    if (!open) return;
    const next = initialValues(link);
    setValues(next);
    setExpiresInput(isoToLocalInput(link?.expires_at));
    setErrors({});
    setShowAdvanced(
      Boolean(
        link &&
          (link.include_submission_in_url || link.open_app_on_mobile || link.utm_enabled || link.expires_at)
      )
    );
  }, [open, link]);

  const set = <K extends keyof LinkFormValues>(key: K, value: LinkFormValues[K]) => {
    setValues((prev) => ({ ...prev, [key]: value }));
    if (errors[key as keyof Errors]) setErrors((prev) => ({ ...prev, [key]: undefined }));
  };

  const submit = async (e: React.FormEvent) => {
    e.preventDefault();
    const nextErrors = validate(values, expiresInput, isEdit);
    setErrors(nextErrors);
    if (Object.keys(nextErrors).length) {
      if (nextErrors.open_app_on_mobile || nextErrors.expires_at) setShowAdvanced(true);
      return;
    }
    setSubmitting(true);
    try {
      const ok = await onSubmit({
        ...values,
        link_title: values.link_title.trim(),
        platform: values.platform.trim(),
        destination_url: values.destination_url.trim(),
        expires_at: localInputToIso(expiresInput),
      });
      if (ok) onClose();
    } finally {
      setSubmitting(false);
    }
  };

  const formId = isEdit ? "edit-link-form" : "new-link-form";

  return (
    <Dialog
      open={open}
      onClose={onClose}
      dismissible={!submitting}
      title={isEdit ? "Edit link" : "New link"}
      description={
        isEdit
          ? "The short code stays the same, so URLs already shared keep working."
          : "One link per destination. Each creator gets their own tracking URL from it."
      }
      footer={
        <>
          <Button variant="secondary" onClick={onClose} disabled={submitting}>
            Cancel
          </Button>
          <Button type="submit" form={formId} loading={submitting} disabled={!isEdit && !shortCodePreview}>
            {isEdit ? "Save changes" : "Create link"}
          </Button>
        </>
      }
    >
      <form id={formId} onSubmit={submit} noValidate className="space-y-4">
        <Field label="Title" error={errors.link_title} hint="Only you and your clients see this.">
          <Input
            value={values.link_title}
            onChange={(e) => set("link_title", e.target.value)}
            placeholder="e.g. Diwali reel — Instagram"
            autoFocus
          />
        </Field>
        <Field label="Platform" error={errors.platform}>
          <Input
            value={values.platform}
            onChange={(e) => set("platform", e.target.value)}
            list="link-platform-suggestions"
            placeholder="e.g. Instagram"
          />
        </Field>
        <datalist id="link-platform-suggestions">
          {PLATFORM_SUGGESTIONS.map((p) => (
            <option key={p} value={p} />
          ))}
        </datalist>
        <Field label="Destination URL" error={errors.destination_url}>
          <Input
            type="url"
            inputMode="url"
            value={values.destination_url}
            onChange={(e) => set("destination_url", e.target.value)}
            placeholder="https://"
          />
        </Field>

        {!isEdit && (
          <p className="text-xs text-slate-600">
            Short code:{" "}
            {shortCodePreview ? (
              <span className="font-mono font-semibold text-slate-800">{shortCodePreview}</span>
            ) : (
              "generating…"
            )}
          </p>
        )}

        <div className="rounded-lg border border-slate-200">
          <button
            type="button"
            onClick={() => setShowAdvanced((v) => !v)}
            aria-expanded={showAdvanced}
            aria-controls={`${formId}-advanced`}
            className="flex w-full items-center justify-between gap-2 px-3 py-2.5 text-left text-sm font-medium text-slate-800"
          >
            Advanced options
            <ChevronDown className={`h-4 w-4 transition-transform ${showAdvanced ? "rotate-180" : ""}`} aria-hidden />
          </button>
          {showAdvanced && (
            <div id={`${formId}-advanced`} className="space-y-4 border-t border-slate-200 px-3 py-3">
              <CheckboxField
                checked={values.include_submission_in_url}
                onChange={(v) => set("include_submission_in_url", v)}
                title="Include submission in the URL"
                description="URLs end with /sub1, /sub2… so one creator can track several posts."
              />
              <div>
                <CheckboxField
                  checked={values.open_app_on_mobile}
                  onChange={(v) => set("open_app_on_mobile", v)}
                  title="Open in the app on phones"
                  description="Opens YouTube, Instagram, TikTok, X, Facebook or Spotify in their app instead of a browser."
                />
                {errors.open_app_on_mobile && (
                  <p role="alert" className="mt-1.5 pl-7 text-sm text-rose-700">
                    {errors.open_app_on_mobile}
                  </p>
                )}
              </div>
              <CheckboxField
                checked={values.utm_enabled}
                onChange={(v) => set("utm_enabled", v)}
                title="Add UTM tags"
                description="Lets the destination's own analytics see the platform, project and creator. Existing UTM tags are kept."
              />
              <Field
                label="Expires"
                optional
                error={errors.expires_at}
                hint="After this, the link shows “Link expired” instead of redirecting."
              >
                <Input
                  type="datetime-local"
                  value={expiresInput}
                  onChange={(e) => {
                    setExpiresInput(e.target.value);
                    if (errors.expires_at) setErrors((p) => ({ ...p, expires_at: undefined }));
                  }}
                />
              </Field>
              {expiresInput && (
                <button
                  type="button"
                  onClick={() => setExpiresInput("")}
                  className="-mt-2 text-sm font-medium text-primary-700 hover:underline"
                >
                  Remove expiry
                </button>
              )}
            </div>
          )}
        </div>
      </form>
    </Dialog>
  );
}

function initialValues(link?: Link | null): LinkFormValues {
  return {
    link_title: link?.link_title ?? "",
    platform: link?.platform ?? "",
    destination_url: link?.destination_url ?? "",
    open_app_on_mobile: link?.open_app_on_mobile ?? false,
    include_submission_in_url: link?.include_submission_in_url ?? false,
    utm_enabled: link?.utm_enabled ?? false,
    expires_at: link?.expires_at ?? null,
  };
}
